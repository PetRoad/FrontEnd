// 띄어쓰기는 무시
const squash = (s: string) => s.replace(/\s/g, '');

export function searchBreeds(query: string) {
  const k = squash(query);
  if (!k) return [];
  return BREEDS.filter((b) => squash(b).includes(k)).sort(
    (a, b) =>
      Number(!squash(a).startsWith(k)) - Number(!squash(b).startsWith(k)),
  );
}
